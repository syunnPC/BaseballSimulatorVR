namespace BaseballSimulatorVR::Data
{
	// Layout of the bundled content (read-only, shipped next to the executable):
	//   Presets/Pitch/PitchSettings.<name>.json          pitch presets
	//   Presets/Pitch/PitchSettings.default.json         template of the user's PitchSettings.user.json
	//   Presets/Environment/EnvironmentSettings.<name>.json
	//   Presets/Environment/EnvironmentSettings.default.json  template of EnvironmentSettings.user.json
	//   Presets/Play/PlaySettings.default.json           template of PlaySettings.user.json
	// The user directory (%LOCALAPPDATA%\BaseballSimulatorVR) holds the *.user.json files plus any
	// file the user customized. A user file with the same entry name as a bundled preset overrides it.
	namespace PresetLayout
	{
		inline constexpr std::wstring_view PresetsDirectoryName = L"Presets";
		inline constexpr std::wstring_view PitchDirectoryName = L"Pitch";
		inline constexpr std::wstring_view EnvironmentDirectoryName = L"Environment";
		inline constexpr std::wstring_view PlayDirectoryName = L"Play";
		inline constexpr std::wstring_view PitchSettingsPrefix = L"PitchSettings.";
		inline constexpr std::wstring_view UserPitchSettingsFileName = L"PitchSettings.user.json";
		inline constexpr std::wstring_view UserEnvironmentSettingsFileName = L"EnvironmentSettings.user.json";
		inline constexpr std::wstring_view UserPlaySettingsFileName = L"PlaySettings.user.json";
		inline constexpr std::wstring_view DefaultPitchSettingsFileName = L"PitchSettings.default.json";
		inline constexpr std::wstring_view DefaultEnvironmentSettingsFileName = L"EnvironmentSettings.default.json";
		inline constexpr std::wstring_view DefaultPlaySettingsFileName = L"PlaySettings.default.json";
		inline constexpr std::wstring_view LegacyPresetBackupDirectoryName = L"LegacyPresetBackup";
		// Label of PitchSettings.user.json files written before displayName existed.
		inline constexpr std::wstring_view UserPitchSettingsDisplayName = L"ユーザー設定";
	} // namespace PresetLayout

	enum class PresetOrigin
	{
		Bundled,
		User
	};

	// One selectable pitch settings entry. Files declaring mirrorForLeftHandedPitcher produce two
	// entries, "<stem>.RHP.json" and "<stem>.LHP.json"; the one for the opposite hand is generated by
	// MirrorPitchSettingsForOppositeHand. Entry names keep the historical file names, so a saved
	// selection such as "PitchSettings.Difficulty.Easy.LHP.json" stays valid.
	struct PitchSettingsEntry final
	{
		std::wstring id{};
		std::filesystem::path sourcePath{};
		PresetOrigin origin{ PresetOrigin::Bundled };
		bool mirrored{ false };
		std::wstring displayName{};
		// Set for entries of files that offer both hands; the UI appends the hand to the label.
		std::optional<bool> pitcherThrowsLeftHanded{};

		[[nodiscard]] bool IsReadOnly() const noexcept
		{
			return origin == PresetOrigin::Bundled;
		}
		[[nodiscard]] std::wstring BuildLabel() const;
	};

	class PresetCatalog final
	{
	  public:
		// bundledPresetsDirectory is the "Presets" folder; either path may be empty.
		PresetCatalog(std::filesystem::path bundledPresetsDirectory, std::filesystem::path userDirectory);

		[[nodiscard]] static bool IsBundledPresetsDirectory(const std::filesystem::path& directory);

		[[nodiscard]] const std::filesystem::path& GetBundledPresetsDirectory() const noexcept
		{
			return m_bundledDirectory;
		}
		[[nodiscard]] const std::filesystem::path& GetUserDirectory() const noexcept
		{
			return m_userDirectory;
		}
		[[nodiscard]] std::filesystem::path GetBundledPitchDirectory() const;
		[[nodiscard]] std::filesystem::path GetBundledEnvironmentDirectory() const;
		[[nodiscard]] std::filesystem::path GetBundledPlayDirectory() const;

		// Bundled entries (Presets/Pitch, recursively, except the *.default.json template) merged with
		// user PitchSettings.*.json files; user entries replace bundled entries with the same id.
		// Sorted by id. Files that cannot be read are skipped and described in warnings.
		[[nodiscard]] std::vector<PitchSettingsEntry> EnumeratePitchSettings(
		    std::vector<std::wstring>* warnings = nullptr) const;
		[[nodiscard]] std::optional<PitchSettingsEntry> FindPitchSettings(std::wstring_view id) const;
		// Entry for a file that is not part of the catalog (for example an explicit path).
		[[nodiscard]] PitchSettingsEntry DescribeFile(const std::filesystem::path& filePath) const;
		// Loads the entry and applies the mirror transform for generated variants.
		[[nodiscard]] std::optional<PitchRuntimeSettings> LoadPitchSettings(
		    const PitchSettingsEntry& entry, std::wstring& errorMessage) const;

		// Resolves an environmentSettingsFile reference: next to the owning file, in the user
		// directory, then in Presets/Environment. "EnvironmentSettings.user.json" falls back to the
		// bundled default when the user file is missing.
		[[nodiscard]] std::filesystem::path ResolveEnvironmentReference(
		    std::wstring_view reference, const std::filesystem::path& owningFile) const;
		// Bundled files are never written: changes go to a same-named user copy (the bundled
		// environment default maps to EnvironmentSettings.user.json).
		[[nodiscard]] std::filesystem::path ResolveEnvironmentSaveTarget(const std::filesystem::path& environmentFile) const;
		[[nodiscard]] std::filesystem::path ResolvePitchSaveTarget(const PitchSettingsEntry& entry) const;
		[[nodiscard]] bool IsBundledPath(const std::filesystem::path& path) const;

		[[nodiscard]] std::filesystem::path GetUserPlaySettingsPath() const;
		[[nodiscard]] std::filesystem::path GetUserEnvironmentSettingsPath() const;
		[[nodiscard]] std::filesystem::path GetUserPitchSettingsPath() const;
		// Bundled template used to create or restore a user settings file (empty if none).
		[[nodiscard]] std::filesystem::path FindBundledDefaultFor(const std::filesystem::path& userFile) const;

		// Creates the user directory and any missing *.user.json file from the bundled defaults.
		// Existing user files are never modified.
		[[nodiscard]] bool EnsureUserFiles(std::wstring& errorMessage) const;

		// Earlier versions copied every bundled preset into the user directory, where those copies
		// shadowed later preset updates (and the app rewrote them). Returns user files whose names
		// match bundled presets or their generated variants; *.user.json files are never included.
		[[nodiscard]] std::vector<std::filesystem::path> FindLegacyProvisionedCopies() const;
		// Moves the given files into <user>/LegacyPresetBackup (a unique sub folder per run) and
		// returns that folder.
		[[nodiscard]] std::optional<std::filesystem::path> MoveToLegacyBackup(
		    const std::vector<std::filesystem::path>& files, std::wstring& errorMessage) const;

	  private:
		void AppendEntriesForFile(const std::filesystem::path& file, PresetOrigin origin,
		    std::vector<PitchSettingsEntry>& entries, std::vector<std::wstring>* warnings) const;

		std::filesystem::path m_bundledDirectory;
		std::filesystem::path m_userDirectory;
		PitchPresetJsonStorage m_storage{};
	};

	[[nodiscard]] bool IsPitchSettingsFileName(std::wstring_view fileName) noexcept;
} // namespace BaseballSimulatorVR::Data
