#pragma once

#include "../Baseball/PitchParameters.hpp"

#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace BaseballSimulatorVR::Data
{
	inline constexpr std::wstring_view DefaultEnvironmentSettingsReference = L"EnvironmentSettings.user.json";

	struct PitchProfileEntry final
	{
		std::wstring name{ L"Pitch" };
		Baseball::PitchParameters pitchParameters{};
	};

	struct PitchRuntimeSettings final
	{
		Baseball::PitchParameters pitchParameters{};
		std::wstring environmentSettingsFile{ DefaultEnvironmentSettingsReference };
		std::vector<PitchProfileEntry> pitchProfiles{};
		int activePitchProfileIndex{ -1 };
		bool randomPitchProfileEnabled{ true };
		bool pitcherThrowsLeftHanded{ false };
		// UI label of the preset ("displayName"); the throwing hand is appended by the UI.
		std::wstring displayName{};
		// When true the catalog also offers the opposite-hand variant generated by
		// MirrorPitchSettingsForOppositeHand, so only one handedness file is shipped.
		bool mirrorForLeftHandedPitcher{ false };
	};

	// Horizontal mirror of a delivery for the other throwing hand: lateral release velocity is
	// negated and the spin axis (an axial vector) maps (x, y, z) -> (x, -y, -z). All other values,
	// including speeds, spin rate and coefficients, are kept, so heights and arrival times match.
	[[nodiscard]] Baseball::PitchParameters MirrorPitchParametersForOppositeHand(
	    const Baseball::PitchParameters& parameters) noexcept;
	[[nodiscard]] PitchRuntimeSettings MirrorPitchSettingsForOppositeHand(const PitchRuntimeSettings& settings);

	class PitchPresetJsonStorage final
	{
	  public:
		// Atomic save that keeps the previous valid file as "<name>.bak". Numbers use the shortest
		// round-trip representation.
		[[nodiscard]] bool SavePitchSettings(
		    std::wstring_view filePath,
		    const PitchRuntimeSettings& settings,
		    std::wstring& errorMessage) const;
		// errorMessage includes the line, column and key of the first problem.
		[[nodiscard]] std::optional<PitchRuntimeSettings> LoadPitchSettings(
		    std::wstring_view filePath,
		    std::wstring& errorMessage) const;
		[[nodiscard]] std::optional<PitchRuntimeSettings> ParsePitchSettings(
		    std::string_view jsonText,
		    std::wstring& errorMessage) const;
		[[nodiscard]] bool Save(std::wstring_view filePath, const Baseball::PitchParameters& pitchParameters, std::wstring& errorMessage) const;
		[[nodiscard]] std::optional<Baseball::PitchParameters> Load(std::wstring_view filePath, std::wstring& errorMessage) const;
	};
} // namespace BaseballSimulatorVR::Data
